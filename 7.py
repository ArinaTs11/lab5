# Задание 7.
# Дан целочисленный массив размера N,
# не содержащий одинаковых чисел.
# Проверить, образуют ли его элементы
# арифметическую прогрессию.
# Если образуют, вывести разность прогрессии,
# если нет, вывести 0.

N = int(input("Введите N: "))

A = list(map(int, input("Введите элементы массива: ").split()))

D = A[1] - A[0]
is_progression = True

for i in range(1, N - 1):
    if A[i + 1] - A[i] != D:
        is_progression = False
        break

if is_progression:
    print("Разность прогрессии:", D)
else:
    print(0)