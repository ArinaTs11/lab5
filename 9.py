# Задание 9.
# Дан массив размера N.
# Найти номер его последнего локального максимума.
# Локальный максимум — это элемент,
# который больше любого из своих соседей.

N = int(input("Введите N: "))

A = list(map(int, input("Введите элементы массива: ").split()))

number = 0

for i in range(N - 2, 0, -1):
    if A[i] > A[i - 1] and A[i] > A[i + 1]:
        number = i + 1
        break

print("Номер последнего локального максимума:", number)