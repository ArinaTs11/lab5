# Задание 5.
# Дан массив A размера N.
# Вывести вначале его элементы с нечетными номерами
# в порядке возрастания номеров, а затем элементы
# с четными номерами в порядке убывания номеров.

N = int(input("Введите N: "))

A = list(map(int, input("Введите элементы массива: ").split()))

for i in range(0, N, 2):
    print(A[i], end=" ")

for i in range(N - 1, 0, -2):
    print(A[i], end=" ")